void st7789_draw_char(uint16_t x, uint16_t y, char c, uint16_t color, uint16_t bg)
{
    if (x + 8 > ST7789_WIDTH || y + 16 > ST7789_HEIGHT) return;
    if (c < 32 || c > 126) c = ' ';

    const uint8_t *bmp = font8x16[c - 32];
    uint16_t char_buf[8 * 16];

    /* Byte swap colors for SPI transmission (MSB first) */
    uint16_t fg_swapped = (color >> 8) | (color << 8);
    uint16_t bg_swapped = (bg >> 8) | (bg << 8);

    for (int r = 0; r < 16; r++) {
        uint8_t line = bmp[r];
        for (int b = 0; b < 8; b++) {
            char_buf[r * 8 + b] = (line & (0x80 >> b)) ? fg_swapped : bg_swapped;
        }
    }

    st7789_set_window(x, y, x + 7, y + 15);
    st7789_write_pixels((const uint8_t *)char_buf, sizeof(char_buf));
}

void st7789_draw_string(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg)
{
    uint16_t cur_x = x;
    uint16_t cur_y = y;

    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += 16;
            if (cur_y + 16 > ST7789_HEIGHT) break;
        } else {
            if (cur_x + 8 > ST7789_WIDTH) {
                cur_x = x;
                cur_y += 16;
                if (cur_y + 16 > ST7789_HEIGHT) break;
            }
            st7789_draw_char(cur_x, cur_y, *str, color, bg);
            cur_x += 8;
        }
        str++;
    }
}

void st7789_draw_string_fb(uint16_t *fb, uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg)
{
    if (!fb) return;
    uint16_t cur_x = x;
    uint16_t cur_y = y;

    /* NOTE: colors are written NATIVE (not byte-swapped) — callers that blit
     * the fb (e.g. map_render's fb_blit) do the wire byte-swap themselves. */

    while (*str) {
        char c = *str;
        if (c == '\n') {
            cur_x = x;
            cur_y += 16;
            if (cur_y + 16 > ST7789_HEIGHT) break;
        } else {
            if (cur_x + 8 > ST7789_WIDTH) {
                cur_x = x;
                cur_y += 16;
                if (cur_y + 16 > ST7789_HEIGHT) break;
            }
            if (c < 32 || c > 126) c = ' ';
            const uint8_t *bmp = font8x16[c - 32];

            for (int r = 0; r < 16; r++) {
                int py = cur_y + r;
                if (py >= ST7789_HEIGHT) continue;
                uint8_t line = bmp[r];
                for (int b = 0; b < 8; b++) {
                    int px = cur_x + b;
                    if (px >= ST7789_WIDTH) continue;
                    fb[py * ST7789_WIDTH + px] = (line & (0x80 >> b)) ? color : bg;
                }
            }
            cur_x += 8;
        }
        str++;
    }
}

void st7789_draw_string_fb_scaled(uint16_t *fb, uint16_t x, uint16_t y,
                                  const char *str, uint8_t scale,
                                  uint16_t color, uint16_t bg)
{
    if (!fb || scale < 1) return;
    uint16_t cur_x = x;
    uint16_t cur_y = y;

    while (*str) {
        char c = *str;
        if (c == '\n') {
            cur_x = x;
            cur_y += 16 * scale;
        } else {
            if (c < 32 || c > 126) c = ' ';
            const uint8_t *bmp = font8x16[c - 32];
            for (int r = 0; r < 16; r++) {
                uint8_t line = bmp[r];
                for (int b = 0; b < 8; b++) {
                    uint16_t col = (line & (0x80 >> b)) ? color : bg;
                    for (int sy = 0; sy < scale; sy++) {
                        int py = cur_y + r * scale + sy;
                        if (py >= ST7789_HEIGHT) continue;
                        for (int sx = 0; sx < scale; sx++) {
                            int px = cur_x + b * scale + sx;
                            if (px >= ST7789_WIDTH) continue;
                            fb[py * ST7789_WIDTH + px] = col;
                        }
                    }
                }
            }
            cur_x += 8 * scale;
        }
        str++;
    }
}

/* ═══════════════════════════════════════════════════════
 *  Backlight & deinit
 * ═══════════════════════════════════════════════════════ */

void st7789_backlight(uint8_t pct)
{
    if (ST7789_PIN_BL < 0) return;
    gpio_set_level(ST7789_PIN_BL, (pct > 0) ? 1 : 0);
}

void st7789_deinit(void)
{
    st7789_wait_dma();
    st7789_backlight(0);
    lcd_cmd(CMD_SLPIN);
    if (spi_dev) {
        spi_bus_remove_device(spi_dev);
        spi_dev = NULL;
    }
    spi_bus_free(ST7789_SPI_HOST);
    initialized = false;
}

